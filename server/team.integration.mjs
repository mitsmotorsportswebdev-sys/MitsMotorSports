test('alumni admin members support optional roles, ordering, and photos', async () => {
  const alumni = await project('alumni')
  const first = await group(alumni, '2025', 0)
  const second = await group(alumni, '2024', 1)
  let response = await admin(`/projects/${alumni.slug}/groups`, 'post').send({ name: '2026' })
  status(response, 201)
  const createdGroup = await Group.findById(response.body.data.id)
  assert.equal(createdGroup.name, '2026')
  assert.equal(createdGroup.order, 2)
  response = await admin(`/groups/${first._id}/members`, 'post').send({ name: 'No role alumnus', role: '', visible: true })
  status(response, 201)
  const created = response.body.data
  response = await admin(`/groups/${first._id}/members`, 'post').send({ name: 'Second alumnus', role: 'Captain', visible: true })
  status(response, 201)
  const secondMember = response.body.data
  response = await admin(`/members/${created.id}/move`, 'post').send({ direction: 'down' })
  status(response, 200)
  value((await Member.find({ group: first._id }).sort({ order: 1 })).map((item) => item.name), ['Second alumnus', 'No role alumnus'], response)
  response = await admin(`/members/${created.id}`, 'patch').send({ name: 'Moved alumnus', role: '', groupId: second._id.toString() })
  status(response, 200)
  value((await Member.findById(created.id)).group.toString(), second._id.toString(), response)
  response = await upload(`/api/admin/members/${created.id}/photo`)
  status(response, 200)
  const imageId = String((await Member.findById(created.id)).image)
  value(response.body.data.imageUrl, `/api/images/${imageId}`, response)
  value(response.body.success, true, response)
  response = await upload(`/api/admin/members/${created.id}/photo`, Buffer.from([0xff, 0xd8, 0xff, 0x03]))
  status(response, 200)
  value(await Image.countDocuments({}), 1, response)
  response = await admin(`/members/${created.id}/photo`, 'delete')
  status(response, 200)
  value(await Image.countDocuments({}), 0, response)
  value(secondMember.role, 'Captain', response)
})

